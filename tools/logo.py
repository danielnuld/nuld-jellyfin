#!/usr/bin/env python3
"""Bake the NULD logo glyphs as vector meshes into logo_data.c: real Michroma / Archivo / IBM Plex Mono outlines,
flattened and triangulated (earcut), so the PS2 draws them sharp at any size without atlas room (the 1280x720
framebuffers leave the GS none). Each glyph: points in font units (y up), triangle indices, contour starts (the
contours are drawn again as anti-aliased lines for smooth edges), advance.

usage: logo.py [OUT.c]  (default: logo_data.c next to the Makefile)   needs: pip install fonttools mapbox-earcut
"""
import sys
from pathlib import Path

import mapbox_earcut as earcut
import numpy as np
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "tools" / "fonts"
# C name, file, variation axes, characters (canvas: A Michroma, B Plex Mono 500, C and D Archivo 800 at 125 %)
SPECS = (("michroma", "Michroma-Regular.ttf", None, "NULD"),
         ("archivo_heavy", "Archivo.ttf", {"wght": 800, "wdth": 125}, "NULD/"),
         ("plex_medium", "IBMPlexMono-Medium.ttf", None, "$nuld"))
STEPS = 10  # segments per curve


class Flat(BasePen):  # contours as closed point lists
    def __init__(self, gs):
        super().__init__(gs)
        self.contours, self.cur = [], []

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _qCurveToOne(self, p1, p2):
        p0 = self.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            self.cur.append(((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
                             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]))

    def _curveToOne(self, p1, p2, p3):
        p0 = self.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            u = 1 - t
            self.cur.append((u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                             u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]))

    def _closePath(self):
        if len(self.cur) > 1 and self.cur[0] == self.cur[-1]:
            self.cur.pop()
        if len(self.cur) >= 3:
            self.contours.append(self.cur)
        self.cur = []

    _endPath = _closePath


def inside(pt, poly):
    x, y, c = pt[0], pt[1], False
    for i in range(len(poly)):
        (x0, y0), (x1, y1) = poly[i - 1], poly[i]
        if (y0 > y) != (y1 > y) and x < (x1 - x0) * (y - y0) / (y1 - y0) + x0:
            c = not c
    return c


def glyph_mesh(contours):
    """Outer contours (even nesting) with their holes (odd), each group triangulated; all points in one list."""
    depth = [sum(inside(c[0], o) for j, o in enumerate(contours) if j != i) for i, c in enumerate(contours)]
    pts, tris, starts = [], [], []
    for i, c in enumerate(contours):
        if depth[i] % 2:
            continue
        holes = [h for j, h in enumerate(contours) if depth[j] == depth[i] + 1 and inside(h[0], c)]
        ring = [c] + holes
        flat = np.array([p for r in ring for p in r], dtype=np.float32)
        ends = np.cumsum([len(r) for r in ring]).astype(np.uint32)
        base = len(pts)
        tris += [base + int(k) for k in earcut.triangulate_float32(flat, ends)]
        for r in ring:
            starts.append(len(pts))
            pts += r
    return pts, tris, starts


def bake(file, axes, chars):
    f = TTFont(str(FONTS / file))
    if axes:
        f = instantiateVariableFont(f, axes)
    gs, cmap, hmtx = f.getGlyphSet(), f.getBestCmap(), f["hmtx"]
    out = []
    for ch in chars:
        name = cmap[ord(ch)]
        pen = Flat(gs)
        gs[name].draw(pen)
        pts, tris, starts = glyph_mesh(pen.contours)
        out.append(dict(ch=ch, pts=pts, tris=tris, starts=starts, adv=hmtx[name][0]))
    os2 = f["OS/2"]
    return out, f["head"].unitsPerEm, os2.sCapHeight or f["hhea"].ascent, os2.sxHeight or 0


def c_source():
    out = ["// Generated by tools/logo.py from Michroma, Archivo, IBM Plex Mono (SIL OFL 1.1, tools/fonts/*OFL.txt). Do not edit.",
           '#include "logo_data.h"']
    for cname, file, axes, chars in SPECS:
        glyphs, upm, cap, xh = bake(file, axes, chars)
        for g in glyphs:
            k = f"{cname}_{ord(g['ch'])}"
            out.append(f"static const short {k}_v[] = {{" + ",".join(f"{round(x)},{round(y)}" for x, y in g["pts"]) + "};")
            out.append(f"static const unsigned short {k}_t[] = {{" + ",".join(map(str, g["tris"])) + "};")
            out.append(f"static const unsigned short {k}_c[] = {{" + ",".join(map(str, g["starts"])) + "};")
        out.append(f"static const vglyph {cname}_glyphs[] = {{")
        for g in glyphs:
            k = f"{cname}_{ord(g['ch'])}"
            out.append(f"\t{{'{g['ch']}', {k}_v, {len(g['pts'])}, {k}_t, {len(g['tris']) // 3}, {k}_c, {len(g['starts'])}, {g['adv']}}},")
        out.append("};")
        out.append(f"const vfont vfont_{cname} = {{ {cname}_glyphs, {len(glyphs)}, {upm}, {cap}, {xh} }};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    dst = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "logo_data.c"
    dst.write_text(c_source(), encoding="utf-8", newline="\n")
    print(dst, dst.stat().st_size, "bytes")
